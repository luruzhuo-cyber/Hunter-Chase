import { test, expect } from '@playwright/test';

test('creates isolated task, trains, evaluates and compares through the real console', async ({page}) => {
  test.setTimeout(180000);
  await page.goto('http://127.0.0.1:8766/');
  await expect(page.getByRole('heading',{name:'猎场训练工作台'})).toBeVisible();
  await page.locator('#create [name=protocol]').selectOption('selfplay');
  await page.locator('#create [name=steps]').fill('16');
  await page.locator('#create [name=max_ticks]').fill('10');
  await page.getByRole('button',{name:'创建实验',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('已创建');
  await page.getByRole('button',{name:'开始训练',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:120000});
  await expect(page.locator('#fps')).not.toHaveText('—');
  await expect(page.locator('#log')).toContainText('generation=1 side=hunter');
  await page.getByRole('button',{name:'独立评估',exact:true}).click();
  await page.locator('#seeds').fill('2');
  await page.getByRole('button',{name:'运行独立评估',exact:true}).click();
  await expect(page.locator('#evaluation')).toContainText('2 局',{timeout:60000});
  await expect(page.locator('#evaluation')).toContainText('确定性 通过');
  const runId=await page.locator('#title').innerText();
  await page.locator('#evalSide').selectOption('runner');
  await page.locator('#opponent').selectOption(runId);
  await page.getByRole('button',{name:'运行独立评估',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:60000});
  await expect(page.locator('#evaluation')).toContainText('测试 runner');
  await page.locator('.compare-check').first().check();
  await page.getByRole('button',{name:'比较所选实验',exact:true}).click();
  await expect(page.locator('#comparison table')).toBeVisible();
  await page.screenshot({path:'artifacts/training-console.png',fullPage:true});
  await page.getByRole('button',{name:'从完整代恢复',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:120000});
  await expect(page.locator('#phase')).toContainText('第 2 代');
  await page.locator('#create [name=steps]').fill('250000');
  await page.getByRole('button',{name:'创建实验',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('已创建');
  await page.getByRole('button',{name:'开始训练',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await page.getByRole('button',{name:'停止任务',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('已停止',{timeout:60000});
  await expect(page.getByRole('button',{name:'从完整代恢复',exact:true})).toBeDisabled();
});
