import {test,expect} from '@playwright/test';

test('phase1 trains only hunter, evaluates every fixed map and resumes frozen source',async({page})=>{
  test.setTimeout(180000);
  await page.goto('http://127.0.0.1:8766/');
  await expect(page.locator('#create [name=protocol]')).toHaveValue('hunter-phase1');
  await expect(page.locator('#create [name=hunter_speed_ratio]')).toHaveValue('1.35');
  await page.locator('#create [name=steps]').fill('16');
  await page.locator('#create [name=max_ticks]').fill('10');
  await page.getByRole('button',{name:'创建实验',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('已创建');
  const id=await page.locator('#title').innerText();
  await page.getByRole('button',{name:'开始训练',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:90000});
  await expect(page.locator('#phase')).toContainText('猎人');
  await expect(page.locator('#log')).toContainText('side=hunter');
  await expect(page.locator('#log')).not.toContainText('side=runner');
  await expect(page.getByTestId('training-map-table').locator('tbody tr')).toHaveCount(10);
  await page.getByRole('button',{name:'独立评估',exact:true}).click();
  await expect(page.locator('#evalSide')).toBeDisabled();
  await page.locator('#seeds').fill('10');
  await page.getByRole('button',{name:'运行独立评估',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:90000});
  await expect(page.locator('#evaluation')).toContainText('10 局');
  await expect(page.locator('#evaluation')).toContainText('确定性通过');
  await expect(page.getByTestId('evaluation-map-table').locator('tbody tr')).toHaveCount(10);
  const first=await (await page.request.get(`http://127.0.0.1:8766/api/runs/${id}`)).json();
  expect(first.config.hunter_speed_ratio).toBe(1.35);
  expect(first.codeSnapshot.codeHash).toMatch(/^[a-f0-9]{64}$/);
  expect(first.evaluation.runnerPolicy).toBe('frozen-waypoint-v1');
  expect(first.evaluation.perMap.every((map:any)=>map.episodes===1)).toBeTruthy();
  await page.getByRole('button',{name:'从完整代恢复',exact:true}).click();
  await expect(page.locator('#state')).toHaveText('运行中');
  await expect(page.locator('#state')).toHaveText('已完成',{timeout:90000});
  await expect(page.locator('#phase')).toContainText('第 2 代');
  const resumed=await (await page.request.get(`http://127.0.0.1:8766/api/runs/${id}`)).json();
  expect(resumed.config).toEqual(first.config);
  expect(resumed.codeSnapshot.codeHash).toBe(first.codeSnapshot.codeHash);
  await page.getByRole('button',{name:'训练总览',exact:true}).click();
  await page.screenshot({path:'artifacts/phase1-live-lifecycle.png',fullPage:true});
});
